#!/usr/bin/env python3
import argparse
import json
import time
import urllib.error
import urllib.request


def post_json(url, payload):
    data = json.dumps(payload).encode("utf-8")
    request = urllib.request.Request(
        url,
        data=data,
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return response.read().decode("utf-8")
    except urllib.error.HTTPError as error:
        body = error.read().decode("utf-8", errors="replace")
        raise SystemExit(f"upload failed: status={error.code} body={body}") from error


def main():
    parser = argparse.ArgumentParser(description="Post coverage.py JSON output to oAT.")
    parser.add_argument("--endpoint", required=True, help="oAT service base URL, for example http://localhost:8080")
    parser.add_argument("--project-id", required=True)
    parser.add_argument("--app-id", required=True)
    parser.add_argument("--coverage-json", required=True, help="Path generated by: coverage json -o coverage.json")
    parser.add_argument("--version-number")
    parser.add_argument("--commit-id")
    parser.add_argument("--branch")
    parser.add_argument("--case-name")
    parser.add_argument("--build-id")
    parser.add_argument("--test-stage", default="unknown")
    args = parser.parse_args()

    with open(args.coverage_json, "r", encoding="utf-8") as handle:
        coverage_data = json.load(handle)

    payload = {
        "projectId": args.project_id,
        "appId": args.app_id,
        "language": "PYTHON",
        "versionNumber": args.version_number,
        "commitId": args.commit_id,
        "branch": args.branch,
        "caseName": args.case_name,
        "buildId": args.build_id,
        "testStage": args.test_stage,
        "timestamp": int(time.time() * 1000),
        "payload": coverage_data,
    }
    url = args.endpoint.rstrip("/") + "/api/v2/ingest/coverage"
    print(post_json(url, payload))


if __name__ == "__main__":
    main()
